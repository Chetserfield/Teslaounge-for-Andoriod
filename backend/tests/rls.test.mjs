import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('multi-user database permissions and moderation',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 grant usage on schema public,auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;`);
 await db.exec(await readFile(new URL('../../supabase/migrations/202611010001_community.sql',import.meta.url),'utf8'));
 const a='11111111-1111-4111-8111-111111111111',b='22222222-2222-4222-8222-222222222222',p='33333333-3333-4333-8333-333333333333';
 const as=async(role,id='')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec(`set role ${role}`);};
 const denied=async(sql,params=[])=>assert.rejects(db.query(sql,params));
 await db.query('insert into auth.users values ($1),($2)',[a,b]);
 await as('anon');await denied('insert into public.profiles(id,nickname) values ($1,\'fake\')',[a]);
 await as('authenticated',a);
 await db.query('insert into public.profiles(id,nickname) values ($1,\'Alice\')',[a]);
 await denied('insert into public.profiles(id,nickname) values ($1,\'imposter\')',[b]);
 await db.query("insert into public.posts(id,title,body,category) values ($1,'hello','shared','오너 생활')",[p]);
 await denied('update public.posts set hidden=true where id=$1',[p]);
 await denied('update public.posts set author_id=$1 where id=$2',[b,p]);
 await denied("insert into public.posts(title,body,category) values ('','x','오너 생활')");
 await as('authenticated',b);
 await db.query('insert into public.profiles(id,nickname) values ($1,\'Bob\')',[b]);
 assert.equal((await db.query('select title from public.posts')).rows[0].title,'hello');
 assert.equal((await db.query("update public.posts set title='stolen' where id=$1 returning id",[p])).rows.length,0);
 assert.equal((await db.query('delete from public.posts where id=$1 returning id',[p])).rows.length,0);
 assert.equal((await db.query("update public.profiles set nickname='stolen' where id=$1 returning id",[a])).rows.length,0);
 await db.query("insert into public.comments(post_id,body) values ($1,'reply')",[p]);
 await db.query('insert into public.reactions(post_id) values ($1)',[p]);
 await denied('insert into public.reactions(post_id) values ($1)',[p]);
 await as('authenticated',a);
 assert.equal((await db.query('select * from public.reactions')).rows.length,0);
 assert.equal(Number((await db.query('select public.reaction_count($1) as n',[p])).rows[0].n),1);
 assert.equal((await db.query("update public.comments set body='stolen' returning id")).rows.length,0);
 await as('anon');assert.equal((await db.query('select * from public.posts')).rows.length,1);
 await denied("insert into public.comments(post_id,body) values ($1,'guest')",[p]);
 await denied('select * from public.reactions');
 await as('postgres');await db.query('update public.posts set hidden=true where id=$1',[p]);
 await as('authenticated',b);assert.equal((await db.query('select * from public.comments')).rows.length,0);
 await denied("insert into public.comments(post_id,body) values ($1,'hidden reply')",[p]);
 assert.equal(Number((await db.query('select public.reaction_count($1) as n',[p])).rows[0].n),0);
 await denied("insert into public.providers(name,region,category,approved) values ('fake','서울','PPF',true)");
 await as('postgres');
 const v=(await db.query("insert into public.providers(name,region,category) values ('test','서울','PPF') returning id")).rows[0].id;
 await db.query("insert into public.advertisements(provider_id,title,approved,starts_at,ends_at) values ($1,'test ad',true,now()-interval '1 day',now()+interval '1 day')",[v]);
 await as('anon');assert.equal((await db.query('select * from public.providers')).rows.length,0);assert.equal((await db.query('select * from public.advertisements')).rows.length,0);
 await as('postgres');await db.query('update public.providers set approved=true where id=$1',[v]);
 await as('anon');assert.equal((await db.query('select * from public.providers')).rows.length,1);assert.equal((await db.query('select * from public.advertisements')).rows.length,1);
 await as('postgres');await db.query("update public.advertisements set ends_at=now()-interval '1 hour'");
 await as('anon');assert.equal((await db.query('select * from public.advertisements')).rows.length,0);
 await db.close();
});
